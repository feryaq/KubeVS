import { generateKubeJs, importRecipeJson } from '@kubevs/recipe-model';
import { createHash } from 'node:crypto';
import { isDeepStrictEqual } from 'node:util';

export function recipeRevision(json: unknown): string {
  return createHash('sha256').update(JSON.stringify(json)).digest('hex');
}

/** Existing JSON fields only: no implicit arrays, prototype traversal or wildcard replacements. */
export function recipePointer(json: unknown, pointer: string): unknown {
  let value = json;
  for (const part of pointerParts(pointer)) {
    if (typeof value !== 'object' || value === null || !Object.hasOwn(value, part))
      throw new Error(`Recipe field does not exist: ${pointer}`);
    value = (value as Record<string, unknown>)[part];
  }
  return value;
}

function pointerParts(pointer: string): string[] {
  if (!pointer.startsWith('/') || /~(?![01])/u.test(pointer))
    throw new Error('Use a JSON Pointer to an existing field, e.g. /sequence/0/ingredients/1.');
  const parts = pointer
    .slice(1)
    .split('/')
    .map((part) => part.replaceAll('~1', '/').replaceAll('~0', '~'));
  if (parts.some((part) => ['__proto__', 'prototype', 'constructor'].includes(part)))
    throw new Error('Unsafe recipe field path.');
  return parts;
}

export function patchRecipeDefinition(
  recipeId: string,
  json: unknown,
  edits: readonly { path: string; expected: unknown; value: unknown }[],
): { json: unknown; code: string; sourceRevision: string } {
  requireRecipeId(recipeId, 'Recipe ID');
  if (!json || typeof json !== 'object' || Array.isArray(json) || !('type' in json))
    throw new Error('Expected a complete recipe JSON with type.');
  const patched = JSON.parse(JSON.stringify(json)) as Record<string, unknown>;
  const paths: string[] = [];
  for (const edit of edits) {
    if (
      paths.some(
        (path) =>
          path === edit.path ||
          path.startsWith(`${edit.path}/`) ||
          edit.path.startsWith(`${path}/`),
      )
    )
      throw new Error('Recipe patch paths must not overlap.');
    paths.push(edit.path);
    if (!isDeepStrictEqual(recipePointer(patched, edit.path), edit.expected))
      throw new Error(`Recipe field conflict at ${edit.path}; read the live definition again.`);
    const parts = pointerParts(edit.path);
    const key = parts.pop();
    const parent = parts.length
      ? recipePointer(
          patched,
          '/' + parts.map((part) => part.replaceAll('~', '~0').replaceAll('/', '~1')).join('/'),
        )
      : patched;
    if (
      !key ||
      typeof parent !== 'object' ||
      parent === null ||
      (Array.isArray(parent) && !/^(0|[1-9]\d*)$/u.test(key))
    )
      throw new Error('Invalid recipe field path.');
    (parent as Record<string, unknown>)[key] = edit.value;
  }
  if (typeof patched.type !== 'string' || !isRecipeId(patched.type))
    throw new Error('Recipe type must remain a namespaced serializer ID.');
  return {
    json: patched,
    sourceRevision: recipeRevision(json),
    code: `// Generated by KubeVS: explicit nested recipe edit.\nServerEvents.recipes(event => {\n  event.remove({ id: ${JSON.stringify(recipeId)} })\n  event.custom(${JSON.stringify(patched, null, 2).split('\n').join('\n  ')}).id(${JSON.stringify(recipeId)})\n})\n`,
  };
}

export function verifyRecipeFields(
  json: unknown,
  checks: readonly { path: string; expected: unknown }[],
): { matches: boolean; failures: readonly string[] } {
  const failures: string[] = [];
  for (const check of checks) {
    try {
      if (!isDeepStrictEqual(recipePointer(json, check.path), check.expected))
        failures.push(check.path);
    } catch {
      failures.push(check.path);
    }
  }
  return { matches: failures.length === 0, failures };
}

const RESOURCE_ID = /^[a-z0-9_.-]+:[a-z0-9_./-]+$/u;

export interface RecipeReplacement {
  readonly targetId: string;
  readonly sourceId: string;
  readonly recipeType: string;
  readonly code: string;
  readonly warnings: readonly string[];
}

/**
 * Builds a complete managed KubeJS script which installs the source recipe under the target ID.
 * The source ID is intentionally never used as the generated recipe ID.
 */
export function buildRecipeReplacement(
  targetId: string,
  sourceId: string,
  sourceJson: unknown,
): RecipeReplacement {
  requireRecipeId(targetId, 'Recipe ID to replace');
  requireRecipeId(sourceId, 'Template recipe ID');

  const imported = importRecipeJson(targetId, sourceJson);
  const errors = imported.issues.filter((issue) => issue.severity === 'error');
  if (errors.length > 0) {
    throw new Error(errors.map((issue) => `${issue.path}: ${issue.message}`).join('\n'));
  }

  const expression = generateKubeJs(imported.recipe);
  return {
    targetId,
    sourceId,
    recipeType: imported.recipe.recipeType,
    warnings: imported.issues
      .filter((issue) => issue.severity === 'warning')
      .map((issue) => `${issue.path}: ${issue.message}`),
    code: [
      '// Generated by KubeVS: exact recipe replacement by ID.',
      `// Definition copied from ${sourceId}; replaced in game by ${targetId}.`,
      'ServerEvents.recipes(event => {',
      indent(expression, 2),
      '})',
      '',
    ].join('\n'),
  };
}

export function isRecipeId(value: string): boolean {
  return RESOURCE_ID.test(value);
}

function requireRecipeId(value: string, label: string): void {
  if (!isRecipeId(value)) throw new Error(`${label}: expected namespace:path`);
}

function indent(value: string, spaces: number): string {
  const prefix = ' '.repeat(spaces);
  return value
    .split('\n')
    .map((line) => `${prefix}${line}`)
    .join('\n');
}
